# Writes src/engine/fillerModel.ts from a trained checkpoint.
import torch, base64, numpy as np, sys
ch=int(sys.argv[1]); sd=torch.load(f'/tmp/cc/ml/net{ch}.pt')
dils=[1,2,4,8]
def b64(t): return base64.b64encode(t.detach().numpy().astype('<f4').tobytes()).decode()
layers=[]
for i,d in enumerate(dils):
    w=sd[f'c.{i}.weight']; layers.append(dict(w=b64(w),b=b64(sd[f'c.{i}.bias']),inCh=w.shape[1],outCh=w.shape[0],k=w.shape[2],dil=d))
w=sd['o.weight']; layers.append(dict(w=b64(w),b=b64(sd['o.bias']),inCh=w.shape[1],outCh=w.shape[0],k=1,dil=1))
src="// Generated by the training script: filler-sound detector trained on the AMI Meeting Corpus\n// (CC BY 4.0, https://groups.inf.ed.ac.uk/ami/corpus/). Do not edit by hand.\n\n"
src+="export const MODEL = {\n  layers: [\n"+"".join(f"    {{ inCh: {l['inCh']}, outCh: {l['outCh']}, k: {l['k']}, dil: {l['dil']}, w: '{l['w']}', b: '{l['b']}' }},\n" for l in layers)+"  ],\n};\n"
open('/home/user/recut/src/engine/fillerModel.ts','w').write(src); print('ok',len(src))
